//! File Processing Pipeline for Armature Framework
//!
//! Provides a fluent API for file processing operations including:
//! - Image manipulation (resize, crop, rotate, format conversion)
//! - PDF generation and manipulation
//! - Archive operations (zip/unzip)
//! - Format detection and conversion
//!
//! ## Quick Start
//!
//! ```rust,no_run
//! # #[cfg(feature = "images")]
//! # async fn example() -> Result<(), Box<dyn std::error::Error>> {
//! use armature_files::image::{ImageOp, ResizeFilter};
//! use armature_files::{OutputFormat, Pipeline, Position};
//!
//! let result = Pipeline::new()
//!     .load("input.jpg")
//!     .await?
//!     .image(ImageOp::Resize {
//!         width: 800,
//!         height: 600,
//!         filter: ResizeFilter::Lanczos3,
//!     })
//!     .image(ImageOp::TextWatermark {
//!         text: "© 2025".into(),
//!         position: Position::BottomRight,
//!         font_size: 24.0,
//!         color: [255, 255, 255, 180],
//!         // `None` falls back to `Pipeline::with_font`, then to the
//!         // embedded font (requires the `embedded-font` feature).
//!         font: None,
//!     })
//!     // WebP encoding is lossless; there is no quality parameter.
//!     .convert(OutputFormat::WebP)
//!     .save("output.webp")
//!     .await?;
//!
//! println!(
//!     "wrote {} bytes in {} ms",
//!     result.data.len(),
//!     result.processing_time_ms
//! );
//! # Ok(())
//! # }
//! ```
//!
//! The same operations are available as shorthand — `.resize(800, 600)`,
//! `.watermark("© 2025", Position::BottomRight)`, `.to_jpeg(85)`,
//! `.to_png()`, `.to_webp()` — when the defaults suit you.
//!
//! ## PDF generation
//!
//! ```rust,no_run
//! # #[cfg(feature = "pdf")]
//! # fn example() -> Result<(), Box<dyn std::error::Error>> {
//! use armature_files::pdf::{FontSize, PdfBuilder};
//!
//! let pdf = PdfBuilder::new()
//!     .title("Report")
//!     .add_heading("Hello, World!", FontSize::H1)
//!     .add_text("Generated by armature-files.")
//!     .add_page_break()
//!     .add_table(&[
//!         vec!["Item", "Qty"],
//!         vec!["Widget", "2"],
//!     ])
//!     .build()?;
//!
//! println!("{} byte PDF", pdf.data.len());
//! # Ok(())
//! # }
//! ```
//!
//! ## Architecture
//!
//! ```text
//! ┌─────────────────────────────────────────────────────────────┐
//! │                         Pipeline                             │
//! │  ┌─────────┐   ┌─────────┐   ┌─────────┐   ┌─────────┐     │
//! │  │  Load   │──▶│ Process │──▶│ Convert │──▶│  Save   │     │
//! │  └─────────┘   └─────────┘   └─────────┘   └─────────┘     │
//! │       │              │              │              │         │
//! │       ▼              ▼              ▼              ▼         │
//! │  ┌─────────┐   ┌─────────┐   ┌─────────┐   ┌─────────┐     │
//! │  │  File   │   │  Image  │   │  Format │   │  File   │     │
//! │  │  Bytes  │   │   PDF   │   │  Codec  │   │ Storage │     │
//! │  └─────────┘   └─────────┘   └─────────┘   └─────────┘     │
//! └─────────────────────────────────────────────────────────────┘
//! ```

